-- Match Your Colors: capes (the Recolor Cape option): which rows of a cape's material LUT show, how much, and how
-- much of each its tint covers.
--
-- A cape kit is one piece (slot 1, type 0, body any, no unit of its own) on the armor's cape-mount unit; the game
-- binds its material LUT to the mount material's LUT slot like an armor piece's, so the recolor path is the
-- armor's. The cape shader (base material dafef1303e987a57, disassembled 2026-10-07: KB match-your-colors-cape-tint)
-- picks the LUT row per texel from the kit's decal scalar fields: the outside takes the first of R, G, B at least
-- 0.496 (byte SET) as row 1, 2 or 3, else row 0; the inside takes row 1 where R is set, else row 4. A is the cape's
-- opacity; the cloth only shows inside one outline the capes share (OUTLINE, from the 17 capes whose A covers 47-50%
-- of the texture; tattered capes lie inside it).
-- The kit's cape LUT (16 x H, one row per material row; rows past H read zeros) tints each row: its base color goes
-- toward column 3's RGB by t = |w| x saturate(c6.w x (g' - c6.z)) (w: column 3 w; c6: column 6; g': the gradient's
-- R at the texel, 1 - it when w < 0). United in Equality's purple is such a tint. A tinted row is two colors: its
-- base and its tint row (key '<cape LUT>:<row>', the material row with column 0 the tint; src/recolor.lua refits
-- column 3 of a copy of the cape LUT). Its other columns place the emblem-sheet layers (their colors are the sheet's).
--
-- The areas come from a GRID x GRID sample of the fields and of the gradient (the nearest texel of the smallest mip
-- with both sides at least GRID; RGBA8, RGBA16F, BC7, BC3 or BC4): a cell counts when it is inside the outline and its
-- A is set; the outside weighs W_OUT and the inside W_IN (the back shows the whole outside, the front part of the
-- inside), split between the row's base (1 - t) and its tint (t, in 1 / TINT_STEPS steps: integer sums). Area =
-- weight / the weight of every counted cell of a row the LUT has. research/capes.py is the reference
-- (tests/fixtures/capes.lua). Nothing here runs per frame: Capes.analyse runs inside a recolor job.
local ffi = require('ffi')
local bit = require('bit')
local band, rshift = bit.band, bit.rshift

local Capes = {}

