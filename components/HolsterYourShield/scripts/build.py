"""Test and build Holster Your Shield.

    python -B scripts/build.py           tests, then releases/Holster-Your-Shield-v<VERSION>.zip

Needs a Bingus Shared Loader checkout (BINGUS_SHARED_LOADER, default: the workspace's ongoing-work checkout
publication/resilience-v1/checkouts/BingusSharedLoader, else BingusSharedLoader beside this repository) for
scripts/archive.py and scripts/build_addon.py, a LuaJIT (HD2_LUAJIT, default: the workspace build, else `luajit` on
PATH) and the installed game's bin/lua51.dll for the in-game VM tests (tests/game_lua.py, HD2_LUA51_DLL).
"""

from __future__ import annotations

import json
import os
from pathlib import Path
import shutil
import struct
import subprocess
import sys
import uuid
import zipfile

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parents[1]
WORKSPACE = HERE.parent


def loader_checkout() -> Path:
    if 'BINGUS_SHARED_LOADER' in os.environ:
        return Path(os.environ['BINGUS_SHARED_LOADER'])
    ongoing = WORKSPACE / 'publication/resilience-v1/checkouts/BingusSharedLoader'
    return ongoing if (ongoing / 'scripts/build_addon.py').exists() else WORKSPACE / 'BingusSharedLoader'


sys.path.insert(0, str(loader_checkout() / 'scripts'))
from archive import ARCHIVE, make_archive, resource_hash  # noqa: E402
from build_addon import entry_source  # noqa: E402

VERSION = '1.0'
LUA_NAME = 'mods/cowboybingus/holster_your_shield'
GUID = '8e98b68e-4525-442c-b603-21fc7f2f5037'
TITLE = 'Holster Your Shield v' + VERSION
DESCRIPTION = ('Press Backpack Function to put the Ballistic Shield or the Directional Shield on your back while '
               'you keep a one-handed weapon in hand; press again to take it back. No options. Steam build '
               '25480438. Requires Bingus Shared Loader v18+.')
GAME_LUA = HERE / 'tests/game_lua.py'
MOD = 'holster_your_shield.lua'
# Local copies that must stay byte-identical to the workspace's canonical ones (checked when present).
CANONICAL = {'tests/frame_budget.lua': 'PerformanceBaseline/frame_budget.lua',
             'tests/game_lua.py': 'PerformanceBaseline/game_lua.py',
             'tests/hostile_vm.lua': 'BingusSharedRuntime/hostile_vm.lua',
             'src/bingus_runtime.lua': 'BingusSharedRuntime/runtime/bingus_runtime.lua',
             'src/bingus_memory.lua': 'BingusSharedRuntime/runtime/bingus_memory.lua'}
# Vendored Bingus Shared Runtime files, assembled ahead of the mod in this order. The mod writes no memory, so it
# vendors the core and the read side only; bingus_memory.lua verifies the game build.
RUNTIME_FILES = ('bingus_runtime.lua', 'bingus_memory.lua')
# Names the mod's sources must never contain: memory writes, protection changes, code or thread creation,
# library loading, the game's Lua network namespaces.
FORBIDDEN = ('WriteProcessMemory', 'VirtualProtect', 'VirtualAlloc', 'FlushInstructionCache', 'CreateRemoteThread',
             'LoadLibrary', 'Network.', 'RPC.')


def assemble() -> bytes:
    """One plaintext addon entry: the re-entry guard, the vendored runtime files, then the mod. The entry carries
    the loader's discovery declaration on its first line."""
    marker = '-- HD2-Addon: ' + LUA_NAME
    sources = {name: (HERE / 'src' / name).read_text(encoding='utf-8') for name in RUNTIME_FILES}
    mod = (HERE / 'src' / MOD).read_text(encoding='utf-8')
    if not mod.startswith(marker + '\n'):
        raise ValueError(MOD + ' must begin with its HD2-Addon declaration')
    mod = mod.split('\n', 1)[1]  # the entry carries the declaration once, on its own first line
    lines = [marker,
             '-- Holster Your Shield v%s for Steam build 25480438. Generated by scripts/build.py from %s; edit those.'
             % (VERSION, ', '.join('src/' + n for n in RUNTIME_FILES + (MOD,))),
             "if rawget(_G, 'HolsterYourShieldInstalled') then return end",
             'local bingus_runtime = (function()', sources['bingus_runtime.lua'].rstrip('\n'), 'end)()',
             'local bingus_memory = (function()', sources['bingus_memory.lua'].rstrip('\n'), 'end)()',
             'local Holster = (function()', mod.rstrip('\n'), 'end)()',
             'Holster.install(bingus_runtime, bingus_memory.new(bingus_runtime))']
    for line in lines:
        if '\r' in line:
            raise ValueError('sources must use LF line endings')
    return ('\n'.join(lines) + '\n').encode('utf-8')


def luajit() -> Path:
    if 'HD2_LUAJIT' in os.environ:
        return Path(os.environ['HD2_LUAJIT'])
    workspace = WORKSPACE / 'tools/src/LuaJIT/src/luajit.exe'
    return workspace if workspace.exists() else Path(shutil.which('luajit') or workspace)


def run(args: list) -> str:
    result = subprocess.run([str(a) for a in args], capture_output=True, text=True, cwd=HERE)
    output = (result.stdout + result.stderr).strip()
    if result.returncode or 'PASS' not in output:
        raise RuntimeError(f'{args}: {output}')
    return [line for line in output.splitlines() if 'PASS' in line][0]


def test() -> list[str]:
    text = (HERE / 'src' / MOD).read_text(encoding='utf-8')
    for word in FORBIDDEN:
        if word in text:
            raise ValueError(f'{MOD}: forbidden name {word}')
    for local, shared in CANONICAL.items():
        canonical = WORKSPACE / shared
        if canonical.exists() and canonical.read_bytes() != (HERE / local).read_bytes():
            raise ValueError(f'{local} differs from the canonical {shared}')
    results = []
    lua = luajit()
    entry = HERE / 'build/entry-check.lua'
    entry.parent.mkdir(parents=True, exist_ok=True)
    entry.write_bytes(assemble())
    for vm in ([lua], [sys.executable, GAME_LUA]):
        results.append(run(vm + [HERE / 'tests/test_mod.lua', HERE]))
        results.append(run(vm + [HERE / 'tests/test_hostile.lua', HERE]))
        results.append(run(vm + [HERE / 'tests/compile_entry.lua', entry]))
        results.append(run(vm + [HERE / 'tests/test_entry.lua', entry]))
    return results


def build(output: Path) -> Path:
    body = entry_source(LUA_NAME, assemble())
    lua = struct.pack('<II', len(body), 2) + body
    option = {'Name': TITLE, 'Description': DESCRIPTION, 'Include': ['Addon']}
    manifest = {'Version': 1, 'Guid': str(uuid.UUID(GUID)), 'Name': TITLE, 'Description': DESCRIPTION,
                'Options': [option]}
    files = {'INSTALL.txt': (HERE / 'INSTALL.txt').read_bytes()}
    thumbnail = HERE / 'assets/thumbnail.png'
    if thumbnail.exists():
        files['thumbnail.png'] = thumbnail.read_bytes()
        manifest['IconPath'] = option['Image'] = 'thumbnail.png'
    files.update({
        'manifest.json': (json.dumps(manifest, indent=2) + '\n').encode(),
        'Addon/' + ARCHIVE: make_archive({resource_hash(LUA_NAME): lua}),
        'Addon/' + ARCHIVE + '.stream': b'',
        'Addon/' + ARCHIVE + '.gpu_resources': b'',
    })
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, 'w', compression=zipfile.ZIP_DEFLATED) as archive:
        for path, payload in sorted(files.items()):
            info = zipfile.ZipInfo(path, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, payload)
    return output


if __name__ == '__main__':
    for line in test():
        print(line)
    print(build(HERE / 'releases' / f'Holster-Your-Shield-v{VERSION}.zip'))
