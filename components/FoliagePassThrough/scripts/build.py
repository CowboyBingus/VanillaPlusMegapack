"""Test and build Foliage Pass-Through.

    python scripts/build.py

Runs the tests, then writes releases/Foliage-Pass-Through-v1.0.zip (the release build). Where the developer's test-build
files are present (src/shot_log.lua and its companions, not part of the public repository), it also tests and writes
the test build ZIP, which adds a shot log, an in-mission overlay and an F8 vanilla switch.

Needs a Bingus Shared Loader checkout beside this repository (or its path in BINGUS_SHARED_LOADER) for
scripts/archive.py and scripts/build_addon.py, a LuaJIT (HD2_LUAJIT, default: the workspace build, else `luajit` on
PATH) and the installed game's bin/lua51.dll for the in-game VM runs (tests/game_lua.py, HD2_LUA51_DLL).
"""

from __future__ import annotations

import json
import os
from pathlib import Path
import shutil
import struct
import subprocess
import sys
import uuid
import zipfile

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parents[1]
WORKSPACE = HERE.parent
LOADER = Path(os.environ.get('BINGUS_SHARED_LOADER', WORKSPACE / 'BingusSharedLoader'))
sys.path.insert(0, str(LOADER / 'scripts'))
from archive import ARCHIVE, make_archive, resource_hash  # noqa: E402
from build_addon import entry_source  # noqa: E402

VERSION = '1.0'
TEST_BUILD = 'test2'
LUA_NAME = 'mods/cowboybingus/foliage_pass_through'
GUID = 'a0d670e9-b388-4388-9f8f-e82da5b99b32'
TITLE = 'Foliage Pass-Through v' + VERSION
DESCRIPTION = ("Player rockets, missiles, launcher rounds and stratagem ordnance pass through tree canopies and bushes "
               "instead of exploding in them; trunks, the ground and enemies still stop them. Steam build 25480438. "
               "Requires Bingus Shared Loader v18 or newer.")
TEST_DESCRIPTION = ("TEST BUILD. " + DESCRIPTION.split(' Steam build')[0] + " Logs what every explosive shot hits and "
                    "draws it in the mission; F8 switches between the change and vanilla. Steam build 25480438. "
                    "Requires Bingus Shared Loader v18 or newer.")
GAME_LUA = HERE / 'tests/game_lua.py'
MOD = 'foliage_pass_through.lua'
# Local copies that must stay byte-identical to the workspace's canonical ones (checked when present).
CANONICAL = {'tests/frame_budget.lua': 'PerformanceBaseline/frame_budget.lua',
             'tests/game_lua.py': 'PerformanceBaseline/game_lua.py',
             'tests/hostile_vm.lua': 'BingusSharedRuntime/hostile_vm.lua',
             'src/bingus_runtime.lua': 'BingusSharedRuntime/runtime/bingus_runtime.lua',
             'src/bingus_memory.lua': 'BingusSharedRuntime/runtime/bingus_memory.lua',
             'src/bingus_write.lua': 'BingusSharedRuntime/runtime/bingus_write.lua'}
RUNTIME_FILES = ('bingus_runtime.lua', 'bingus_memory.lua', 'bingus_write.lua')
# Test builds only, in order: the shot log's tables, its overlay and the log itself.
SHOT_FILES = (('ShotTables', 'shot_tables.lua'), ('ShotView', 'shot_view.lua'), ('Shots', 'shot_log.lua'))
FORBIDDEN = ('VirtualProtect', 'VirtualAlloc', 'FlushInstructionCache', 'CreateRemoteThread', 'LoadLibrary')


def has_test_build() -> bool:
    return all((HERE / 'src' / name).exists() for _, name in SHOT_FILES)


def source(name: str) -> str:
    return (HERE / 'src' / name).read_text(encoding='utf-8')


def wrapped(local: str, name: str) -> list:
    return ['local %s = (function()' % local, source(name).rstrip('\n'), 'end)()']


def assemble(test_build: bool = False) -> bytes:
    """One plaintext addon entry: the second-copy check, the vendored runtime files, the targets, (test builds) the
    shot log's files, then the mod, installed with the runtime's memory api extended by its checked writes."""
    marker = '-- HD2-Addon: ' + LUA_NAME
    mod = source(MOD)
    if not mod.startswith(marker + '\n'):
        raise ValueError(MOD + ' must begin with its HD2-Addon declaration')
    mod = mod.split('\n', 1)[1]
    files = RUNTIME_FILES + ('foliage_targets.lua',) + (tuple(f for _, f in SHOT_FILES) if test_build else ()) + (MOD,)
    lines = [marker,
             '-- Foliage Pass-Through v%s%s for Steam build 25480438. Generated by scripts/build.py from %s; edit those.'
             % (VERSION, ' (' + TEST_BUILD + ')' if test_build else '', ', '.join('src/' + n for n in files)),
             "if rawget(_G, 'FoliagePassThrough') then return end"]
    lines += wrapped('bingus_runtime', 'bingus_runtime.lua')
    lines += wrapped('bingus_memory', 'bingus_memory.lua')
    lines += wrapped('bingus_write', 'bingus_write.lua')
    lines += wrapped('Targets', 'foliage_targets.lua')
    if test_build:
        for local, name in SHOT_FILES:
            lines += wrapped(local, name)
    lines += ['local Mod = (function()', mod.rstrip('\n'), 'end)()', 'Mod.TARGETS = Targets']
    if test_build:
        lines.append('Mod.install(bingus_write.extend(bingus_memory.new(bingus_runtime)), {diagnostics = Shots, '
                     'diagnostics_options = {runtime = bingus_runtime, tables = ShotTables, view_module = ShotView}})')
    else:
        lines.append('Mod.install(bingus_write.extend(bingus_memory.new(bingus_runtime)))')
    return ('\n'.join(lines) + '\n').encode('utf-8')


def luajit() -> Path:
    if 'HD2_LUAJIT' in os.environ:
        return Path(os.environ['HD2_LUAJIT'])
    workspace = WORKSPACE / 'tools/src/LuaJIT/src/luajit.exe'
    return workspace if workspace.exists() else Path(shutil.which('luajit') or workspace)


def run(args: list) -> str:
    result = subprocess.run([str(a) for a in args], capture_output=True, text=True, cwd=HERE)
    output = (result.stdout + result.stderr).strip()
    if result.returncode or 'PASS' not in output or 'ERROR' in output:
        raise RuntimeError(f'{args}: {output}')
    return [line for line in output.splitlines() if 'PASS' in line][-1]


def check_sources(test_build: bool) -> None:
    names = [MOD, 'foliage_targets.lua'] + ([name for _, name in SHOT_FILES] if test_build else [])
    for name in names:
        text = source(name)
        for word in FORBIDDEN:
            if word in text:
                raise ValueError('Unexpected executable memory mutation in %s: %s' % (name, word))
    for local, shared in CANONICAL.items():
        canonical = WORKSPACE / shared
        if canonical.exists() and canonical.read_bytes() != (HERE / local).read_bytes():
            raise ValueError(f'{local} differs from the canonical {shared}')


def test() -> list[str]:
    test_build = has_test_build()
    if test_build and (HERE / 'scripts/make_tables.py').exists():
        subprocess.run([sys.executable, '-I', str(HERE / 'scripts/make_tables.py')], check=True, capture_output=True)
    check_sources(test_build)
    entries = {}
    for kind, flag in (('release', False), ('test', True)):
        if flag and not test_build:
            continue
        entry = HERE / ('build/entry-%s.lua' % kind)
        entry.parent.mkdir(parents=True, exist_ok=True)
        entry.write_bytes(assemble(flag))
        entries[kind] = entry
    suites = ['tests/test_mod.lua'] + (['tests/test_shots.lua'] if test_build else [])
    results = []
    for vm in ([luajit()], [sys.executable, GAME_LUA]):
        for name in suites:
            results.append(run(vm + [HERE / name, HERE]))
        for entry in entries.values():
            results.append(run(vm + [HERE / 'tests/compile_entry.lua', entry]))
            results.append(run(vm + [HERE / 'tests/test_entry.lua', entry]))
    return results


def build(output: Path, test_build: bool = False) -> Path:
    body = entry_source(LUA_NAME, assemble(test_build))
    lua = struct.pack('<II', len(body), 2) + body
    title = TITLE + (' (%s)' % TEST_BUILD if test_build else '')
    description = TEST_DESCRIPTION if test_build else DESCRIPTION
    option = {'Name': title, 'Description': description, 'Include': ['Addon']}
    manifest = {'Version': 1, 'Guid': str(uuid.UUID(GUID)), 'Name': title, 'Description': description,
                'Options': [option]}
    install = HERE / ('INSTALL-test.txt' if test_build else 'INSTALL.txt')
    files = {'INSTALL.txt': install.read_bytes(),
             'manifest.json': (json.dumps(manifest, indent=2) + '\n').encode(),
             'Addon/' + ARCHIVE: make_archive({resource_hash(LUA_NAME): lua}),
             'Addon/' + ARCHIVE + '.stream': b'',
             'Addon/' + ARCHIVE + '.gpu_resources': b''}
    thumbnail = HERE / 'assets/thumbnail.png'
    if thumbnail.exists():
        files['thumbnail.png'] = thumbnail.read_bytes()
        manifest['IconPath'] = option['Image'] = 'thumbnail.png'
        files['manifest.json'] = (json.dumps(manifest, indent=2) + '\n').encode()
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, 'w', compression=zipfile.ZIP_DEFLATED) as archive:
        for path, payload in sorted(files.items()):
            info = zipfile.ZipInfo(path, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, payload)
    return output


if __name__ == '__main__':
    for line in test():
        print(line)
    print(build(HERE / 'releases' / f'Foliage-Pass-Through-v{VERSION}.zip'))
    if has_test_build():
        print(build(HERE / 'releases' / f'Foliage-Pass-Through-v{VERSION}-{TEST_BUILD}.zip', True))
