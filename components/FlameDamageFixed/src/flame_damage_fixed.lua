-- Returns the loaded shared effect's data address, or nil and a reason. Reads only.
function Fix.resolve_effect(api, exe)
    local root = pointer(api, exe + RESOURCE_ROOT_RVA)
    local manager = root and pointer(api, root + 0x3f8)
    if not manager then return nil, 'resource manager unavailable' end
    local types, type_count, type_buckets = pointer(api, manager + 0x2f0), api.u32(manager + 0x300), api.u32(manager + 0x304)
    if not type_count or type_count > 4096 then return nil, 'resource type table unavailable' end
    local entry = chain(api, types, 0xd0, 0xc8, type_buckets, PARTICLES[1], PARTICLES[2], type_buckets or 0)
    if not entry then return nil, 'particles type not registered' end
    local names, name_buckets = pointer(api, entry + 0x28), api.u32(entry + 0x3c)
    local slots = api.u32(entry + 0x20)
    if not slots or slots > 1048576 then return nil, 'particle name table unavailable' end
    local name = chain(api, names, 24, 0x10, name_buckets, EFFECT[1], EFFECT[2], slots)
    if not name then return nil, 'flame effect not loaded' end
    local value = api.u32(name + 8)
    if not value or value == NOT_LOADED or value > 1048576 then return nil, 'flame effect pending' end
    local records = pointer(api, entry + 0x10)
    local data = records and pointer(api, records + value * 160)
    local size = records and api.u32(records + value * 160 + 0x18)
    if not data or size ~= EFFECT_SIZE then return nil, 'unexpected effect record' end
    return data
end

-- Checks the loaded effect against the shipped header and layout, and every patched word against its
-- shipped or fixed value. Word reads only: nothing is allocated.
function Fix.check_effect(api, data)
    for i, word in ipairs(Fix.HEADER) do
        if api.u32(data + 4 * (i - 1)) ~= word then return false, 'effect header changed' end
    end
    for _, system in ipairs(Fix.SYSTEMS) do
        if api.u32(data + system[1] + 0x100) ~= system[2] then return false, 'effect layout changed' end
    end
    local pending = 0
    for _, row in ipairs(Fix.PATCHES) do
        local word = api.u32(data + row.o)
        if word ~= row.v and word ~= row.t then return false, 'unknown value at ' .. row.o end
        if word ~= row.t then pending = pending + 1 end
    end
    return true, pending
end

-- Writes the fixed value of every patched word that still holds the shipped one.
function Fix.apply_effect(api, data)
    local ok, pending = Fix.check_effect(api, data)
    if not ok then return false, pending end
    if pending == 0 then return true, 0 end
    if not api.writable_data(data, EFFECT_SIZE) then return false, 'effect memory not writable private data' end
    local writes = 0
    for _, row in ipairs(Fix.PATCHES) do
        if api.u32(data + row.o) ~= row.t then
            if not api.write_raw(data + row.o, row.tb) then return false, 'effect write failed at ' .. row.o end
            writes = writes + 1
        end
    end
    for _, row in ipairs(Fix.PATCHES) do
        if api.u32(data + row.o) ~= row.t then return false, 'effect verify failed at ' .. row.o end
    end
    return true, writes
end

-- ===== 3: self-hit fix (private Havok system groups) =====

-- A system group can take up to 2047; the game hands them out lowest first (at most 63 were in use in
-- busy missions), so each tracked weapon takes one from the top that the allocator still marks free.
local GROUP_UNIT = 2097152 -- 2^21: group 1 in a filter info
local BLOCK_BODIES = 409   -- bodies per read (65440 B)
local SPAN_GAP = 64        -- kept bodies closer than this many records share one read
local W_FLAGS, W_FILTER, W_ID, W_ACTOR, W_UNIT = 17, 27, 28, 36, 37 -- u32 words of a 160 B body record
local HITTABLE = {}
for _, layer in ipairs(Fix.FLAME_ROW) do HITTABLE[layer] = true end

local function words_of(layers)
    local w = {0, 0, 0, 0}
    for _, layer in ipairs(layers) do
        local i = math.floor(layer / 32) + 1
        w[i] = w[i] + 2 ^ (layer % 32)
    end
    return w
end
local FLAME_WORDS = words_of(Fix.FLAME_ROW)

-- The world's collision filter must be the known hknpGroupCollisionFilter with layer 11's recorded row
-- (the kept bodies are the ones this row can hit). Once per session: 8 reads. Returns the filter or nil, reason.
function Fix.check_filter(api, exe)
    local filter = pointer(api, exe + PHYS.FILTER_PTR)
    if not filter then return nil, 'collision filter unavailable' end
    if u64(api, filter) ~= exe + PHYS.FILTER_VTABLE then return nil, 'collision filter type changed' end
    for i = 1, 4 do
        if api.u32(filter + PHYS.MATRIX + 16 * PHYS.FLAME_LAYER + 4 * (i - 1)) ~= FLAME_WORDS[i] then
            return nil, 'flame layer row changed'
        end
    end
    return filter
end

-- The weapon's family: its parent unit (the Lumberer hull) or itself when it has none, and every descendant
-- (first-child / next-sibling links) except avatar subtrees, so a seated pilot is never included. Unit handles
-- go to out[1..n] (and out.set); returns n, or nil and a reason. Reads only.
function Fix.family(api, exe, handle, out, stack)
    local registry = pointer(api, exe + PHYS.UNITS)
    local objects = registry and pointer(api, registry + PHYS.UNIT_OBJECTS)
    if not objects then return nil, 'unit registry unavailable' end
    local unit = pointer(api, objects + 8 * (handle % 4194304))
    if not unit or api.u32(unit + PHYS.UNIT_HANDLE) ~= handle then return nil, 'weapon unit not found' end
    local set = out.set
    for key in pairs(set) do set[key] = nil end
    local n, depth = 0, 1
    stack[1] = pointer(api, unit + PHYS.UNIT_PARENT) or unit
    while depth > 0 do
        local node = stack[depth]
        depth = depth - 1
        if not (api.u32(node + PHYS.UNIT_RESOURCE) == Fix.AVATAR[1] and api.u32(node + PHYS.UNIT_RESOURCE + 4) == Fix.AVATAR[2]) then
            local own = api.u32(node + PHYS.UNIT_HANDLE)
            if not own then return nil, 'unit unreadable' end
            n = n + 1
            if n > MAX_FAMILY then return nil, 'family too large' end
            out[n], set[own] = own, true
            local child = pointer(api, node + PHYS.UNIT_CHILD)
            while child do
                depth = depth + 1
                if depth > MAX_FAMILY then return nil, 'family too large' end
                stack[depth] = child
                child = pointer(api, child + PHYS.UNIT_SIBLING)
            end
        end
    end
    for i = n + 1, #out do out[i] = nil end
    return n
end

-- Starts a body scan for a family: every physics world's body array up to its index bound. Reads only.
function Fix.scan_begin(api, exe, job)
    job.worlds, job.w, job.i, job.n, job.done, job.spans = 0, 1, 0, 0, false, 0
    for w = 0, 3 do
        local world = pointer(api, exe + PHYS.WORLDS + PHYS.WORLD_STRIDE * w)
        if world and u64(api, world) == exe + PHYS.WORLD_VTABLE then
            local bodies, size, limit = pointer(api, world + PHYS.BODIES), api.u32(world + PHYS.BODIES + 8),
                api.u32(world + PHYS.BODY_LIMIT)
            if bodies and size and limit and limit <= size and size <= 1048576 then
                job.worlds = job.worlds + 1
                job.bases[job.worlds], job.limits[job.worlds] = bodies, limit
            end
        end
    end
    if job.worlds == 0 then return nil, 'no physics world' end
    return true
end

-- Groups the kept bodies (in scan order) into spans that one read covers: same body array, at most
-- BLOCK_BODIES records, gaps under SPAN_GAP. Span s covers kept bodies span_k[s] .. span_k[s + 1] - 1.
local function build_spans(job)
    local s = 0
    for k = 1, job.n do
        local first = s > 0 and job.index[job.span_k[s]] or nil
        if s == 0 or job.span_base[s] ~= job.base[k] or job.index[k] - job.index[k - 1] > SPAN_GAP
            or job.index[k] - first + 1 > BLOCK_BODIES then
            s = s + 1
            job.span_k[s], job.span_base[s] = k, job.base[k]
        end
    end
    job.span_k[s + 1], job.spans = job.n + 1, s
end

-- Advances a body scan by up to `blocks` block reads and keeps the family's bodies that the flame can hit
-- and whose subsystem and don't-collide are 0 (bits the game may use are never touched), in no group or in the
-- weapon's own group g (kept as marked). Returns true when the scan is complete, false while it continues, or
-- nil and a reason.
function Fix.scan_step(api, job, set, blocks, g)
    while blocks > 0 and job.w <= job.worlds do
        local base, limit, first = job.bases[job.w], job.limits[job.w], job.i
        if first >= limit then
            job.w, job.i = job.w + 1, 0
        else
            local count = math.min(BLOCK_BODIES, limit - first)
            local words = api.load(base + PHYS.BODY * first, PHYS.BODY * count)
            if not words then return nil, 'body array unreadable' end
            blocks = blocks - 1
            for k = 0, count - 1 do
                local o = 40 * k
                local unit = words[o + W_UNIT]
                if set[unit] and words[o + W_FLAGS] % 4 ~= 0 and words[o + W_ID] % 16777216 == first + k then
                    local filter = words[o + W_FILTER]
                    local group, low = math.floor(filter / GROUP_UNIT), filter % GROUP_UNIT
                    if low < 128 and HITTABLE[low] and (group == 0 or group == g) then
                        local n = job.n + 1
                        if n > MAX_BODIES then return nil, 'too many own bodies' end
                        job.n, job.base[n], job.index[n], job.layer[n] = n, base, first + k, low
                        job.actor[n], job.unit[n], job.marked[n] = words[o + W_ACTOR], unit, group ~= 0
                    end
                end
            end
            job.i = first + count
        end
    end
    job.done = job.w > job.worlds
    if job.done then build_spans(job) end
    return job.done
end

-- region = {base, limit} of the last committed private read-write region checked in this frame.
local function writable(api, region, target)
    if region[1] and target >= region[1] and target + 4 <= region[2] then return true end
    local base, size = api.writable_region(target)
    if not base then return false end
    region[1], region[2] = base, base + size
    return true
end

-- Walks the kept bodies span by span (one read per span) and classifies each against group g:
--   'own'    grouped (g) on the layer the scan saw          'free'    still group-free: to be grouped
--   'moved'  grouped (g) on another layer (the game switched it, as on destruction)
--   'stale'  no longer the body the scan kept (rebuilt, removed or recycled)
-- visit(k, class, words, offset) is called per body; returns false if a span could not be read.
local function each_body(api, job, g, visit)
    for s = 1, job.spans do
        local k0, k1 = job.span_k[s], job.span_k[s + 1] - 1
        local first = job.index[k0]
        local words = api.load(job.span_base[s] + PHYS.BODY * first, PHYS.BODY * (job.index[k1] - first + 1))
        if not words then return false end
        for k = k0, k1 do
            local o = 40 * (job.index[k] - first)
            local class
            if words[o + W_ID] % 16777216 ~= job.index[k] or words[o + W_ACTOR] ~= job.actor[k]
                or words[o + W_UNIT] ~= job.unit[k] or words[o + W_FLAGS] % 4 == 0 then
                class = 'stale'
            else
                local filter = words[o + W_FILTER]
                local group, low = math.floor(filter / GROUP_UNIT), filter % GROUP_UNIT
                if g and group == g and low < 128 then
                    class = low == job.layer[k] and 'own' or 'moved'
                elseif filter < 128 and HITTABLE[filter] then
                    class = 'free'
                else
                    class = 'stale' -- the game gave it another group or layer bits: leave it alone
                end
            end
            visit(k, class, words, o)
        end
    end
    return true
end

-- Summary of the kept bodies for group g: counts per class (reads only, one read per span).
local counts = {own = 0, free = 0, moved = 0, stale = 0}
local function tally(k, class) counts[class] = counts[class] + 1 end
function Fix.verify(api, job, g)
    counts.own, counts.free, counts.moved, counts.stale = 0, 0, 0, 0
    if not each_body(api, job, g, tally) then return nil, 'body array unreadable' end
    return counts
end

-- Puts the kept bodies that are still theirs and group-free into group g (only bits 21-31 change). Returns
-- how many carry g afterwards, or nil and a reason.
local mark_state = {api = nil, g = 0, region = nil, marked = 0, failed = nil}
local function mark_one(k, class, words, o)
    local st = mark_state
    if st.failed then return end
    local job = st.job
    job.marked[k] = false
    if class == 'free' then
        local target = job.base[k] + PHYS.BODY * job.index[k] + 4 * W_FILTER
        if not writable(st.api, st.region, target) then st.failed = 'body memory not writable private data' return end
        if not st.api.write_u32(target, words[o + W_FILTER] + st.g * GROUP_UNIT) then st.failed = 'body write failed' return end
        job.marked[k], st.marked = true, st.marked + 1
    elseif class == 'own' then
        job.marked[k], st.marked = true, st.marked + 1
    end
end
function Fix.mark(api, job, g, region)
    region[1], region[2] = nil, nil
    local st = mark_state
    st.api, st.job, st.g, st.region, st.marked, st.failed = api, job, g, region, 0, nil
    if not each_body(api, job, g, mark_one) then return nil, 'body array unreadable' end
    if st.failed then return nil, st.failed end
    return st.marked
end

-- Clears group g from every kept body that still belongs to its unit (same index and unit; the actor may have
-- been rebuilt) and still carries g, whatever its layer. Returns the number cleared, or nil and a reason.
local function unmark_one(k, class, words, o)
    local st = mark_state
    if st.failed then return end
    local job = st.job
    job.marked[k] = false
    local filter = words[o + W_FILTER]
    if words[o + W_ID] % 16777216 == job.index[k] and words[o + W_UNIT] == job.unit[k]
        and math.floor(filter / GROUP_UNIT) == st.g then
        local target = job.base[k] + PHYS.BODY * job.index[k] + 4 * W_FILTER
        if not writable(st.api, st.region, target) then st.failed = 'body memory not writable private data' return end
        if not st.api.write_u32(target, filter - st.g * GROUP_UNIT) then st.failed = 'body write failed' return end
        st.marked = st.marked + 1
    end
end
function Fix.unmark(api, job, g, region)
    region[1], region[2] = nil, nil
    local st = mark_state
    st.api, st.job, st.g, st.region, st.marked, st.failed = api, job, g, region, 0, nil
    if not each_body(api, job, g, unmark_one) then return nil, 'body array unreadable' end
    if st.failed then return nil, st.failed end
    return st.marked
end

-- True when the game's system-group allocator still marks group g free (its bitmap bit set). 7 reads.
function Fix.group_free(api, exe, g)
    local allocator = pointer(api, exe + PHYS.GROUPS)
    if not allocator then return false end
    local capacity, words, bitmap = api.u32(allocator), api.u32(allocator + 4), pointer(api, allocator + 8)
    if capacity ~= PHYS.GROUP_TOP + 1 or not words or words < 1 or words > 64 or not bitmap then return false end
    local word = api.u32(bitmap + 8 * words + 8 * math.floor(g / 64) + 4 * math.floor((g % 64) / 32))
    return word ~= nil and math.floor(word / 2 ^ (g % 32)) % 2 == 1
end

-- Address of the shared flame's instance list entry {count u32, records ptr} in the particle manager,
-- or nil when no instance of it exists. The entry moves when the effect is unregistered, so it is
-- looked up again at every burst start.
function Fix.flame_slot(api, game)
    local world = pointer(api, game + PHYS.WORLD_PTR)
    local manager = world and pointer(api, world + PHYS.PARTICLE_MANAGER)
    if not manager then return nil end
    local entries, count, buckets = pointer(api, manager + 0x1b8), api.u32(manager + 0x1c8), api.u32(manager + 0x1cc)
    if not entries or not count or count == 0 or count > 65536 or not buckets or buckets == 0 or buckets > 1048576 then
        return nil
    end
    local index, value = EFFECT[2] % buckets, nil
    if api.u32(entries + 24 * index + 0x10) == EMPTY_BUCKET then return nil end
    for _ = 1, count + 1 do
        local base = entries + 24 * index
        if api.u32(base) == EFFECT[1] and api.u32(base + 4) == EFFECT[2] then value = api.u32(base + 8) break end
        index = api.u32(base + 0x10)
        if not index or index == CHAIN_END then return nil end
    end
    local mask, lists = api.u32(manager + 0x228), pointer(api, manager + 0x278)
    if not value or not mask or not lists then return nil end
    return lists + 24 * (bit.band(value, mask) % 4294967296)
end

-- Record address of the flame instance with this id (instance record +0x10) in the flame slot, or nil.
function Fix.find_instance(api, slot, id)
    local count, records = api.u32(slot), pointer(api, slot + 8)
    if not count or not records or count > MAX_INSTANCES then return nil end
    for i = 0, count - 1 do
        local record = records + PHYS.INSTANCE * i
        if api.u32(record + PHYS.INSTANCE_ID) == id then return record end
    end
    return nil
end

-- Sets one flame instance's particle systems' query filter info from layer 11 to `value` (layer 11 in the
-- weapon's group). The world's particle-system array is looked up once per instance. `region` carries the last
-- verified writable heap region. Returns the number of systems changed, or nil and a reason.
function Fix.retarget_instance(api, exe, sim, data, region, value)
    if pointer(api, sim + 32) ~= data then return 0 end -- another effect's instance
    local systems, list = api.u32(sim + 40), pointer(api, sim + 48)
    if not systems or not list or systems > MAX_SYSTEMS then return 0 end
    local moved, array_world, array = 0, nil, nil
    for s = 0, systems - 1 do
        local handle = api.u32(list + 80 * s + 52)
        if handle and handle ~= 0 then
            local index, generation, w = handle % 65536, math.floor(handle / 65536) % 256, math.floor(handle / 1073741824)
            if w ~= array_world then
                local wrapper = pointer(api, exe + PHYS.WORLDS + PHYS.WORLD_STRIDE * w)
                local tbl = wrapper and pointer(api, wrapper + PHYS.PS_TABLE)
                array_world, array = w, tbl and pointer(api, tbl + PHYS.PS_ARRAY)
            end
            local ps = array and pointer(api, array + 16 * index)
            local tag = array and api.u32(array + 16 * index + 8)
            if ps and tag and tag % 65536 == index and math.floor(tag / 16777216) == generation
                and api.u32(ps + PHYS.PS_FILTER) == PHYS.FLAME_LAYER then
                if not writable(api, region, ps + PHYS.PS_FILTER) then return nil, 'particle system not writable private data' end
                if not api.write_u32(ps + PHYS.PS_FILTER, value) then return nil, 'particle system write failed' end
                moved = moved + 1
            end
        end
    end
    return moved
end

