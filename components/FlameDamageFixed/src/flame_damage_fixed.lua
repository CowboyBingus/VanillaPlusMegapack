local WEAPON_NAMES = {[0x0736bee2] = 'Lumberer', [0x820cc3ba] = 'Flame Sentry'}

-- log(line) receives one line per notable event (fix applied, refusals), never per frame.
function Fix.new(api, game, exe, log)
    local self = {clock = 0, since_scan = SCAN_SECONDS, tracked = {}, last = {}, weapons = {}, watch_until = nil,
                  slot = nil, data = nil, filter = nil, self_hit_off = nil, region = {}, told = {},
                  scanning = nil}
    log = log or function() end
    local function tell(key, line)
        if not self.told[key] then self.told[key] = true; log(line) end
    end
    -- Once per reason; the reason string itself is the key, so a repeat builds no string.
    local function tell_once(reason, prefix)
        if not self.told[reason] then self.told[reason] = true; log(prefix .. tostring(reason)) end
    end
    local NO_GROUP = 'Self-hit fix skipped: no free Havok system group in ' .. PHYS.GROUP_LOW .. '-' .. PHYS.GROUP_TOP

    local function new_weapon(address, handle, hi)
        return {address = address, handle = handle, name = WEAPON_NAMES[hi] or 'weapon', started = false,
                firing = false, family = {set = {}}, stack = {},
                job = {bases = {}, limits = {}, base = {}, index = {}, layer = {}, actor = {}, unit = {}, marked = {},
                       span_k = {}, span_base = {}, spans = 0, worlds = 0, w = 1, i = 0, n = 0, done = false},
                job_ok = false, next_try = 0, group = nil, marked = false, destroyed = false, instance = nil,
                awaiting = false}
    end

    -- The weapon's bodies leave its group (it is gone, or its vehicle was destroyed).
    local function release(weapon)
        if weapon.marked and weapon.group and weapon.job_ok then
            local cleared, why = Fix.unmark(api, weapon.job, weapon.group, self.region)
            if not cleared then tell_once(why, 'Self-hit group not released: ') end
        end
        weapon.marked = false
    end

    -- Family and body scan for a weapon: the walk now, the scan over the next present frames. A scan while the
    -- bodies are grouped keeps them (as grouped), so nothing is ever left behind.
    local function begin_family(weapon)
        weapon.job_ok = false
        local n, why = Fix.family(api, exe, weapon.handle, weapon.family, weapon.stack)
        if not n then tell_once(why, 'Self-hit fix unavailable: ') return end
        local ok, reason = Fix.scan_begin(api, exe, weapon.job)
        if not ok then tell_once(reason, 'Self-hit fix unavailable: ') return end
        self.scanning = weapon
    end

    -- A grouped weapon's bodies, checked on the weapon scan (every SCAN_SECONDS, one read per span): a body the
    -- game moved to another layer means the vehicle was destroyed (its wreck leaves the group); a rebuilt body
    -- starts a new scan; a body back to group-free is grouped again at the next burst.
    local function check_marks(weapon)
        local c = Fix.verify(api, weapon.job, weapon.group)
        if not c then return end
        if c.moved > 0 then
            release(weapon)
            weapon.destroyed = true
        elseif c.stale > 0 and self.scanning == nil then
            begin_family(weapon)
        end
    end

    -- Tracked spray weapons (Lumberer arms, Flame Sentries) by their instance's state word. Every
    -- SCAN_SECONDS of game time; per-weapon states and families survive the rescan.
    local spare, seen = {}, {}
    function self.scan()
        self.since_scan = 0
        local tracked, previous, last = self.tracked, self.last, spare
        for key in pairs(last) do last[key] = nil end
        for key in pairs(seen) do seen[key] = nil end
        for i = #tracked, 1, -1 do tracked[i] = nil end
        local manager = pointer(api, game + SPRAY_MANAGER_RVA)
        local count = manager and api.u32(manager + 0x38)
        if count and count > 0 and count <= MAX_SPRAYS then
            local entities, instances = pointer(api, manager + 0x60), pointer(api, manager + 0x70)
            if entities and instances then
                for index = 0, count - 1 do
                    local entity = pointer(api, entities + 8 * index)
                    local lo = entity and api.u32(entity)
                    if lo == Fix.TRACKED[1][1] or lo == Fix.TRACKED[2][1] then
                        local hi = api.u32(entity + 4)
                        if hi == Fix.TRACKED[1][2] or hi == Fix.TRACKED[2][2] then
                            local address, handle = instances + 0x218 * index, api.u32(entity + 12)
                            tracked[#tracked + 1] = address
                            last[address] = previous[address]
                            local weapon = self.weapons[address]
                            if not weapon or weapon.handle ~= handle then
                                if weapon then
                                    release(weapon)
                                    if self.scanning == weapon then self.scanning = nil end
                                end
                                weapon = new_weapon(address, handle, hi)
                                self.weapons[address] = weapon
                            end
                            seen[address] = true
                            if #tracked == MAX_TRACKED then break end
                        end
                    end
                end
            end
        end
        for address, weapon in pairs(self.weapons) do
            if not seen[address] then
                release(weapon)
                if self.scanning == weapon then self.scanning = nil end
                self.weapons[address] = nil
            elseif weapon.marked and weapon.job_ok and not weapon.firing then
                check_marks(weapon)
            end
        end
        spare, self.last = previous, last
    end

    -- A free group for this weapon: its own if the allocator still marks it free, else the highest free one
    -- that no other tracked weapon holds.
    local function pick_group(weapon)
        if weapon.group and Fix.group_free(api, exe, weapon.group) then return weapon.group end
        for g = PHYS.GROUP_TOP, PHYS.GROUP_LOW, -1 do
            local taken = false
            for _, other in pairs(self.weapons) do taken = taken or (other ~= weapon and other.group == g) end
            if not taken and Fix.group_free(api, exe, g) then return g end
        end
        return nil
    end

    -- Effect fix (once per burst start of any tracked weapon). The full lookup runs every burst start: the effect
    -- is reloaded with each mission, and a stale shortcut could leave a mission's flame unfixed.
    function self.burst_start()
        local data, why = Fix.resolve_effect(api, exe)
        self.data = data
        if not data then
            tell_once(why, 'Flame effect not fixed: ')
        elseif not (self.patched == data and api.u32(data + Fix.PATCHES[1].o) == Fix.PATCHES[1].t) then
            local ok, detail = Fix.apply_effect(api, data)
            if ok then
                self.patched = data
                if detail > 0 then log('Flame effect fixed (' .. detail .. ' words).') end
            else
                tell_once(detail, 'Flame effect not fixed: ')
            end
        end
        if not self.filter and not self.self_hit_off then
            local filter, reason = Fix.check_filter(api, exe)
            if filter then self.filter = filter else
                self.self_hit_off = reason
                log('Self-hit fix disabled for this session: ' .. tostring(reason))
            end
        end
        self.slot = Fix.flame_slot(api, game)
    end

    -- Self-hit fix for one weapon's new burst. Its own bodies stay grouped from the first burst until the
    -- weapon is gone; a burst only confirms the group (one read per span) and groups bodies found group-free.
    local function weapon_burst(weapon)
        weapon.instance, weapon.awaiting = nil, true
        if not (self.filter and not self.self_hit_off and weapon.job_ok and not weapon.destroyed) then return end
        local c = Fix.verify(api, weapon.job, weapon.group)
        if not c then return end
        if c.moved > 0 then
            release(weapon)
            weapon.destroyed = true
            return
        end
        if c.free > 0 then
            local g = pick_group(weapon)
            if not g then
                tell(NO_GROUP, NO_GROUP)
                return
            end
            if weapon.marked and g ~= weapon.group then release(weapon) end
            weapon.group = g
            local marked, reason = Fix.mark(api, weapon.job, g, self.region)
            if not marked then
                self.self_hit_off = reason
                log('Self-hit fix disabled for this session: ' .. tostring(reason))
                return
            end
            weapon.marked = marked > 0
            if weapon.marked and not weapon.announced then
                weapon.announced = true
                log('Self-hit fix active for the ' .. weapon.name .. ' (' .. marked .. '/' .. weapon.job.n
                    .. ' own bodies in group ' .. g .. ').')
            end
        end
        if c.stale > 0 and self.scanning == nil then begin_family(weapon) end
    end

    -- Firing and briefly after: the weapon's burst instance (spray record +0x24) gets its group.
    local function find_burst_instance(weapon)
        local slot = self.slot or Fix.flame_slot(api, game)
        self.slot = slot
        local id = api.u32(weapon.address + PHYS.SPRAY_INSTANCE)
        if not slot or not id or id == 0 or id == weapon.instance then return end
        local record = Fix.find_instance(api, slot, id)
        if not record then return end
        weapon.instance, weapon.awaiting = id, false
        if weapon.marked and self.data then
            local sim = pointer(api, record + 8)
            local region = self.region
            region[1], region[2] = nil, nil
            local moved, why = 0, nil
            if sim then
                moved, why = Fix.retarget_instance(api, exe, sim, self.data, region,
                    PHYS.FLAME_LAYER + weapon.group * GROUP_UNIT)
            end
            if not moved then
                self.self_hit_off = why
                log('Self-hit fix disabled for this session: ' .. tostring(why))
                release(weapon)
            end
        end
    end

    function self.step(dt)
        self.clock = self.clock + dt
        self.since_scan = self.since_scan + dt
        if self.since_scan >= SCAN_SECONDS then self.scan() end
        local tracked, last = self.tracked, self.last
        local firing, started = false, false
        for i = 1, #tracked do
            local address = tracked[i]
            local state = api.u32(address)
            local previous = last[address]
            last[address] = state
            local weapon = self.weapons[address]
            weapon.firing = state == 1 or state == 2
            weapon.started = weapon.firing and previous ~= 1 and previous ~= 2
            firing = firing or weapon.firing
            started = started or weapon.started
        end
        if started then
            self.burst_start()
            for i = 1, #tracked do
                local weapon = self.weapons[tracked[i]]
                if weapon.started then weapon_burst(weapon) end
            end
        end
        if firing then self.watch_until = self.clock + WATCH_SECONDS end
        local watching = self.watch_until and self.clock <= self.watch_until
        if self.watch_until and not watching then self.watch_until = nil end
        if watching then
            for i = 1, #tracked do
                local weapon = self.weapons[tracked[i]]
                if weapon.firing or weapon.awaiting then find_burst_instance(weapon) end
            end
        end
        -- One family's body scan at a time, a few block reads per frame.
        local weapon = self.scanning
        if weapon then
            local done, why = Fix.scan_step(api, weapon.job, weapon.family.set, SCAN_BLOCKS, weapon.group)
            if done == nil then
                self.scanning = nil
                tell_once(why, 'Self-hit fix unavailable: ')
            elseif done then
                self.scanning, weapon.job_ok = nil, true
                -- Bodies found still grouped (a scan while grouped) keep their group; the weapon stays grouped.
                for k = 1, weapon.job.n do weapon.marked = weapon.marked or weapon.job.marked[k] end
            end
        else
            for i = 1, #tracked do
                local candidate = self.weapons[tracked[i]]
                if not candidate.job_ok and self.clock >= candidate.next_try then
                    candidate.next_try = self.clock + RETRY_SECONDS
                    begin_family(candidate)
                    break
                end
            end
        end
    end
    return self
end

