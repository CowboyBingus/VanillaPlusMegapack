"""Generates src/components/know_your_constellation/kyc_roster_data.h from Know Your Constellation v4.1.1's
roster_data.lua (and checks every unit name against locales/en.lua).

Usage: python -I gen_roster_header.py <component Lua folder> <output header>
"""
import re
import sys

LUA_DIR = sys.argv[1]
OUT = sys.argv[2]


class Parser:
    TOKEN = re.compile(r"""\s+|--[^\n]*|(?P<str>'(?:[^'\\]|\\.)*')|(?P<num>-?(?:0x[0-9a-fA-F]+|\d+(?:\.\d*)?(?:[eE][-+]?\d+)?|\.\d+(?:[eE][-+]?\d+)?))|(?P<name>[A-Za-z_][A-Za-z_0-9]*)|(?P<punct>[{}\[\]=,])""")

    def __init__(self, text):
        self.tokens = []
        at = 0
        while at < len(text):
            m = self.TOKEN.match(text, at)
            if not m:
                raise SystemExit('cannot tokenize at %d: %r' % (at, text[at:at + 40]))
            at = m.end()
            for kind in ('str', 'num', 'name', 'punct'):
                if m.group(kind) is not None:
                    self.tokens.append((kind, m.group(kind)))
        self.i = 0

    def peek(self, k=0):
        return self.tokens[self.i + k] if self.i + k < len(self.tokens) else (None, None)

    def take(self, value=None):
        tok = self.tokens[self.i]
        if value is not None and tok[1] != value:
            raise SystemExit('expected %r, got %r' % (value, tok))
        self.i += 1
        return tok

    def value(self):
        kind, text = self.peek()
        if text == '{':
            return self.table()
        self.take()
        if kind == 'str':
            return text[1:-1]
        if kind == 'num':
            return Number(text)
        if kind == 'name' and text in ('true', 'false'):
            return text == 'true'
        raise SystemExit('unexpected %r' % text)

    def table(self):
        self.take('{')
        array, mapping = [], {}
        while self.peek()[1] != '}':
            kind, text = self.peek()
            if text == '[':
                self.take('[')
                key = self.value()
                self.take(']')
                self.take('=')
                mapping[key.text if isinstance(key, Number) else key] = self.value()
            elif kind == 'name' and self.peek(1)[1] == '=':
                self.take()
                self.take('=')
                mapping[text] = self.value()
            else:
                array.append(self.value())
            if self.peek()[1] == ',':
                self.take(',')
        self.take('}')
        if mapping and array:
            raise SystemExit('mixed table')
        return mapping if mapping else array


class Number:
    def __init__(self, text):
        self.text = text
        self.value = float(int(text, 16)) if text.lower().startswith('0x') else float(text)

    def int(self):
        assert self.value == int(self.value), self.text
        return int(self.value)

    def __repr__(self):
        return self.text


def load_lua_table(path):
    text = open(path, encoding='utf-8').read()
    start = text.index('return') + len('return')
    return Parser(text[start:]).value()


def unit_key(name):
    key = re.sub(r'[^0-9A-Za-z]+', '_', name.lower()).strip('_')
    return 'unit.' + key


def english_strings():
    text = open(LUA_DIR + '/locales/en.lua', encoding='utf-8').read()
    return dict(re.findall(r"\['([^']+)'\]\s*=\s*'([^']*)'", text))


def mask(tags):
    result = 0
    for tag in tags:
        t = tag.int()
        assert 1 <= t <= 31, t
        result |= 1 << t
    return result


def c_double(number):
    text = number.text
    if re.fullmatch(r'-?\d+', text):
        return text + '.0'
    return text


def main():
    data = load_lua_table(LUA_DIR + '/src/roster_data.lua')
    english = english_strings()
    names = data['names']
    out = []
    w = out.append
    w('/* Know Your Constellation v4.1.1\'s roster (roster_data.lua, generated by gen_roster_data.py from Steam build')
    w(' * 25480438, game.dll 2E2C3B7C...; unit names as on the Helldivers wiki), as C tables: generated from that file by')
    w(' * the port\'s gen_roster_header.py, which also checked every name against locales/en.lua. Do not edit by hand.')
    w(' * Indexes are the Lua\'s, 1-based (element 0 unused): names, families, resources. Tag lists are bit masks (bit t for')
    w(' * authored tag t). The groups\' per-difficulty weight overrides are empty in this build and are left out (the')
    w(' * generator checked). Unit weights by difficulty are distinct rows of kKycWeights. */')
    w('#ifndef KYC_ROSTER_DATA_H')
    w('#define KYC_ROSTER_DATA_H')
    w('')
    w('#include "kyc_roster.h"')
    w('')
    assert data['build'] == '25480438'
    # names
    w('/* names[i] = {plural display name, its text key, wiki size class: 1 small, 2 medium, 3 large, 4 massive} */')
    w('static const KycName kKycNames[] = {')
    w('    {NULL, NULL, 0},')
    line = []
    for entry in names:
        name, size = entry[0], entry[1].int()
        assert re.fullmatch(r'[ -~]+', name), name
        key = unit_key(name)
        assert english.get(key) == name, (key, english.get(key), name)
        line.append('{"%s", "%s", %d},' % (name, key, size))
        if len(line) == 3:
            w('    ' + ' '.join(line))
            line = []
    if line:
        w('    ' + ' '.join(line))
    w('};')
    w('#define KYC_NAME_COUNT ((int)(sizeof kKycNames / sizeof kKycNames[0]) - 1)')
    w('')
    commanders = sorted(int(k) for k in data['commanders'])
    hidden = sorted(int(k) for k in data['hidden'])
    hive = data['hive_lord']
    w('static const uint8_t kKycCommanders[] = {%s};' % ', '.join(str(c) for c in commanders))
    w('static const uint8_t kKycHidden[] = {%s};' % ', '.join(str(c) for c in hidden))
    w('#define KYC_HIVE_LORD_TAG %du' % hive['tag'].int())
    w('#define KYC_HIVE_LORD_DIFFICULTY %du' % hive['difficulty'].int())
    w('#define KYC_HIVE_LORD_NAME %du' % hive['name'].int())
    w('')
    # weights: distinct rows over every faction
    weight_rows = []
    weight_index = {}
    for faction in sorted(data['factions'], key=int):
        for unit in data['factions'][faction]['units']:
            assert len(unit[2]) == 10
            row = tuple(c_double(v) for v in unit[2])
            if row not in weight_index:
                weight_index[row] = len(weight_rows)
                weight_rows.append(row)
    w('/* unit weights by difficulty 1 .. 10 */')
    w('static const double kKycWeights[][10] = {')
    for row in weight_rows:
        w('    {%s},' % ', '.join(row))
    w('};')
    w('')
    faction_names = {'2': 'Terminids', '3': 'Automatons', '4': 'Illuminate'}
    for faction in sorted(data['factions'], key=int):
        f = data['factions'][faction]
        tag = faction_names[faction]
        fam = f['families']
        w('/* faction %s: %s */' % (faction, tag))
        w('static const uint32_t kKyc%sFamilies[] = {0,' % tag)
        for k in range(0, len(fam), 8):
            w('    ' + ', '.join('%su' % v.text for v in fam[k:k + 8]) + ',')
        w('};')
        res = f['resources']
        for r in res:
            assert r.int() == 0 or 1 <= r.int() <= len(names)
        w('static const uint8_t kKyc%sResources[] = {0,' % tag)
        for k in range(0, len(res), 20):
            w('    ' + ', '.join(v.text for v in res[k:k + 20]) + ',')
        w('};')
        w('/* units: {family, resource, required tags, excluded tags, weights row} */')
        w('static const KycUnitRow kKyc%sUnits[] = {' % tag)
        line = []
        for unit in f['units']:
            family, resource = unit[0].int(), unit[1].int()
            assert 1 <= family <= len(fam) and 1 <= resource <= len(res)
            row = tuple(c_double(v) for v in unit[2])
            line.append('{%d, %d, 0x%Xu, 0x%Xu, %d},' % (family, resource, mask(unit[3]), mask(unit[4]), weight_index[row]))
            if len(line) == 4:
                w('    ' + ' '.join(line))
                line = []
        if line:
            w('    ' + ' '.join(line))
        w('};')
        w('/* swaps: {tag, source resource, target resource, lowest difficulty, highest difficulty, priority} */')
        w('static const KycSwap kKyc%sSwaps[] = {' % tag)
        line = []
        for rule in f['swaps']:
            vals = [v.int() for v in rule]
            assert 1 <= vals[0] <= 31 and 1 <= vals[1] <= len(res) and 1 <= vals[2] <= len(res)
            assert 0 <= vals[3] <= 255 and 0 <= vals[4] <= 255 and 0 <= vals[5] <= 255
            line.append('{%d, %d, %d, %d, %d, %d},' % tuple(vals))
            if len(line) == 5:
                w('    ' + ' '.join(line))
                line = []
        if line:
            w('    ' + ' '.join(line))
        w('};')
        members = []
        groups = []
        for g in f['groups']:
            pool, category = g[0].int(), g[1].int()
            assert g[3] == [] or g[3] == {}, 'weight overrides are not empty'
            low, high, plo, phi = g[4].int(), g[5].int(), g[6].int(), g[7].int()
            req = mask(g[8])
            start = len(members)
            for member in g[9]:
                family, count = member[0].int(), member[1].int()
                assert 1 <= family <= len(fam) and 1 <= count <= 65535
                members.append((family, count))
            groups.append('{%d, %d, %s, %d, %d, %d, %d, 0x%Xu, %d, %d},' % (pool, category, c_double(g[2]), low, high,
                                                                           plo, phi, req, start, len(members) - start))
        w('/* group members: {family, count} */')
        w('static const KycMember kKyc%sMembers[] = {' % tag)
        for k in range(0, len(members), 12):
            w('    ' + ' '.join('{%d, %d},' % m for m in members[k:k + 12]))
        w('};')
        w('/* groups: {pool, patrol category, weight, lowest and highest difficulty, fewest and most players, required tags,')
        w(' * first member, members} */')
        w('static const KycGroup kKyc%sGroups[] = {' % tag)
        for k in range(0, len(groups), 2):
            w('    ' + ' '.join(groups[k:k + 2]))
        w('};')
        travel = mask(f['travel'])
        summoned = f.get('summoned')
        summoned = summoned.int() if summoned is not None else 0
        f['_c'] = (tag, travel, summoned)
        w('')
    w('#define KYC_COUNT_OF(a) ((int)(sizeof (a) / sizeof (a)[0]))')
    w('#define KYC_FACTION(name, travel, summoned) {kKyc##name##Families, KYC_COUNT_OF(kKyc##name##Families) - 1, \\')
    w('    kKyc##name##Resources, KYC_COUNT_OF(kKyc##name##Resources) - 1, kKyc##name##Units, KYC_COUNT_OF(kKyc##name##Units), \\')
    w('    kKyc##name##Swaps, KYC_COUNT_OF(kKyc##name##Swaps), kKyc##name##Groups, KYC_COUNT_OF(kKyc##name##Groups), \\')
    w('    kKyc##name##Members, travel, summoned}')
    w('/* factions 2 Terminids, 3 Automatons, 4 Illuminate: {..., travel tags, summoned family (0 none)} */')
    w('static const KycFaction kKycFactions[3] = {')
    for faction in sorted(data['factions'], key=int):
        tag, travel, summoned = data['factions'][faction]['_c']
        w('    KYC_FACTION(%s, 0x%Xu, %d),' % (tag, travel, summoned))
    w('};')
    w('')
    w('#endif')
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print('names %d, weight rows %d' % (len(names), len(weight_rows)))
    for faction in sorted(data['factions'], key=int):
        f = data['factions'][faction]
        print('faction %s: families %d resources %d units %d swaps %d groups %d' % (
            faction, len(f['families']), len(f['resources']), len(f['units']), len(f['swaps']), len(f['groups'])))


main()
